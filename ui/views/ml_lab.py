"""AI congestion prediction (experimental, read-only analysis)."""

from __future__ import annotations

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from ml.dataset import FEATURE_LABELS
from ml.predict import explain_prediction, explanation_text, load_model, predict_run, risk_level
from ml.train import MODEL_PATH, InsufficientDataError, build_and_train, save_model
from ui import state
from ui.components import describe, hero, kpis
from visualization import charts
from visualization.theme import ALGO_COLOR, STATUS, TEMPLATE

RISK_COLOR = {"low": STATUS["good"], "medium": STATUS["timeout"], "high": STATUS["drop"]}


@st.cache_resource(show_spinner=False)
def _model(mtime: float):
    return load_model(MODEL_PATH)


def render() -> None:
    hero("Research", "AI Congestion Prediction",
         "An experimental classifier that reads recorded telemetry and estimates the risk that the bottleneck "
         "buffer overflows in the next few hundred milliseconds.")
    st.warning("**Research and learning feature, not a TCP controller.** Predictions are computed after a run "
               "from its recorded telemetry. They never change cwnd or any algorithm state, and no claim is made "
               "that they would improve network performance.", icon=":material/info:")

    mtime = MODEL_PATH.stat().st_mtime if MODEL_PATH.exists() else 0.0
    status = _model(mtime)
    t_use, t_eval, t_train = st.tabs(["Predict on a run", "Model evaluation", "Train / retrain"])
    with t_train:
        _train()
    if not status.ok:
        with t_use:
            st.info(status.message)
        with t_eval:
            st.info(status.message)
        return
    b = status.bundle
    if status.message != "Model loaded.":
        st.caption(status.message)
    with t_eval:
        _evaluation(b)
    with t_use:
        _predict(b)


def _train() -> None:
    st.markdown(
        "Training data is generated by simulating many random networks (bandwidth, delay, buffer relative to BDP, "
        "random loss, 1–3 flows with random algorithms). Evaluation holds out **whole network configurations**, so "
        "overlapping windows from the same run never appear in both training and test data.")
    c1, c2, c3 = st.columns(3)
    n = c1.slider("Network configurations", 12, 72, 32, step=4, key="ml_n")
    seeds = c2.slider("Seeds per configuration", 1, 3, 2, key="ml_seeds")
    dur = c3.slider("Seconds per run", 5, 30, 15, key="ml_dur")
    st.caption(f"{n * seeds} simulations; typically {n * seeds * dur / 30:.0f}–{n * seeds * dur / 12:.0f} s on a laptop.")
    if st.button("Generate data and train", type="primary"):
        bar = st.progress(0.0, text="Starting...")
        try:
            df, bundle = build_and_train(n, tuple(range(1, seeds + 1)), float(dur),
                                         progress=lambda msg, f: bar.progress(min(f, 1.0), text=msg))
            save_model(bundle)
            _model.clear()
            st.success(f"Trained on {len(df):,} windows from {df['run_id'].nunique()} runs; "
                       f"chosen model: {bundle['chosen'].replace('_', ' ')}.")
            st.rerun()
        except InsufficientDataError as exc:
            st.error(f"Not enough usable data: {exc}")
        finally:
            bar.empty()
    st.caption("Command-line equivalent: `python -m ml.train --configs 48 --seeds 1 2`")


def _evaluation(b: dict) -> None:
    s = b["train_summary"]
    ev = b["evaluation"]
    ch = b["chosen"]
    kpis([
        ("Deployed model", ch.replace("_", " "), f"chosen by grouped CV ROC-AUC {b['cv'][ch]['cv_roc_auc']:.3f}"),
        ("Test ROC-AUC", f"{ev[ch]['roc_auc']:.3f}", "held-out network configurations"),
        ("Test F1", f"{ev[ch]['f1']:.3f}", f"threshold {b['threshold']:.2f} (from CV)"),
        ("Brier score", f"{ev[ch]['brier']:.3f}", "probability calibration (lower is better)"),
        ("Data", f"{s['rows']:,} windows", f"{s['runs']} runs · {s['configs']} configurations"),
        ("Positive rate", f"{s['positive_rate'] * 100:.0f}%", "windows followed by an overflow"),
    ])
    st.markdown(f"**Label:** 1 if at least one buffer-overflow drop happens in the next **{b['horizon_s'] * 1000:.0f} ms**. "
                f"**Features:** computed from the preceding **{b['window_s'] * 1000:.0f} ms** only. "
                f"**Split:** {len(s['train_configs'])} configurations for training/CV, {len(s['test_configs'])} held out "
                f"for testing. Trained {b['created_at']} with scikit-learn {b['sklearn_version']}.")
    rows = []
    for k, m in ev.items():
        rows.append({"model": k.replace("_", " ") + (" (deployed)" if k == ch else ""), "precision": m["precision"],
                     "recall": m["recall"], "F1": m["f1"], "ROC-AUC": m["roc_auc"], "PR-AUC": m["pr_auc"],
                     "Brier": m["brier"], "TP": m["tp"], "FP": m["fp"], "TN": m["tn"], "FN": m["fn"]})
    st.dataframe(pd.DataFrame(rows), hide_index=True, width="stretch",
                 column_config={c: st.column_config.NumberColumn(format="%.3f")
                                for c in ("precision", "recall", "F1", "ROC-AUC", "PR-AUC", "Brier")})
    rule = ev.get("baseline_queue_rule", {}).get("rule", "")
    st.caption(f"Baselines: 'majority' always predicts the most common training label; 'queue rule' predicts "
               f"congestion when {rule} (threshold tuned on training data).")
    c1, c2, c3 = st.columns(3)
    with c1:
        m = ev[ch]
        fig = go.Figure(go.Heatmap(z=[[m["tn"], m["fp"]], [m["fn"], m["tp"]]], x=["predicted 0", "predicted 1"],
                                   y=["actual 0", "actual 1"], colorscale=[[0, "#161a21"], [1, ALGO_COLOR["tahoe"]]],
                                   text=[[m["tn"], m["fp"]], [m["fn"], m["tp"]]], texttemplate="%{text}",
                                   showscale=False))
        fig.update_layout(template=TEMPLATE, height=300, title="Confusion matrix (test)")
        fig.update_yaxes(autorange="reversed", rangemode="normal")
        st.plotly_chart(fig, width="stretch")
    with c2:
        cal = pd.DataFrame(b["calibration"])
        fig = go.Figure()
        fig.add_trace(go.Scatter(x=[0, 1], y=[0, 1], mode="lines", line=dict(dash="dot", color="#6f7684"),
                                 name="perfect"))
        fig.add_trace(go.Scatter(x=cal["mean_predicted"], y=cal["observed_rate"], mode="lines+markers",
                                 marker=dict(size=8), line=dict(color=ALGO_COLOR["newreno"], width=2),
                                 name="model", text=cal["count"], hovertemplate="n=%{text}<extra></extra>"))
        fig.update_layout(template=TEMPLATE, height=300, title="Calibration (test)", xaxis_title="predicted",
                          yaxis_title="observed", showlegend=False)
        st.plotly_chart(fig, width="stretch")
    with c3:
        imp = pd.Series(b["permutation_importance"]).sort_values()
        fig = go.Figure(go.Bar(x=imp.values, y=[FEATURE_LABELS[k] for k in imp.index], orientation="h",
                               marker=dict(color=ALGO_COLOR["tahoe"], cornerradius=3)))
        fig.update_layout(template=TEMPLATE, height=300, title="Permutation importance (ROC-AUC drop)",
                          margin=dict(l=200), yaxis_title="", xaxis_title="")
        fig.update_yaxes(rangemode="normal")
        st.plotly_chart(fig, width="stretch")
    with st.expander("Logistic-regression coefficients (standardised features)"):
        st.dataframe(pd.DataFrame({"feature": [FEATURE_LABELS[k] for k in b["lr_coefficients"]],
                                   "coefficient": list(b["lr_coefficients"].values())}).sort_values(
            "coefficient", key=abs, ascending=False), hide_index=True, width="stretch")


def _predict(b: dict) -> None:
    runs = [r for r in reversed(state.history()) if r.result is not None and not r.result.samples.empty]
    if not runs:
        st.info("Run a simulation first (any page); its telemetry can then be analysed here.")
        return
    labels = {r.run_id: f"{r.run_id} · {r.source} · {describe(r.config)[:80]}" for r in runs}
    rid = st.selectbox("Run", list(labels), format_func=labels.get, key="ml_run")
    res = state.get_record(rid).result
    pred = predict_run(b, res)
    if pred.empty:
        st.info("This run is too short for a full feature window.")
        return
    h = b["horizon_s"]
    act = pred["actual"].fillna(0).to_numpy()
    st.plotly_chart(charts.risk_chart(pred["t"].to_numpy(), pred["prob"].to_numpy(), act, h), width="stretch")
    known = pred[pred["actual"].notna()]
    if len(known):
        from ml.evaluate import classification_metrics
        m = classification_metrics(known["actual"].to_numpy(), known["prob"].to_numpy(), b["threshold"])
        st.caption(f"On this run: precision {m['precision']:.2f}, recall {m['recall']:.2f}, "
                   f"ROC-AUC {m['roc_auc']:.2f} over {m['n']} windows (this run may resemble training data, so treat "
                   f"it as an illustration; the held-out evaluation is on the other tab).")
    t = st.slider("Inspect the prediction at time (s)", float(pred["t"].min()), float(pred["t"].max()),
                  float(pred["t"].iloc[len(pred) // 2]), step=0.01, key="ml_t")
    row = pred.iloc[(pred["t"] - t).abs().argmin()]
    lvl = risk_level(row["prob"])
    c1, c2 = st.columns([1, 2])
    with c1:
        st.markdown(f"<div class='tv-kpi'><div class='l'>Congestion risk at t = {row['t']:.2f} s</div>"
                    f"<div class='v' style='color:{RISK_COLOR[lvl]}'>{lvl.upper()}</div>"
                    f"<div class='h'>p = {row['prob']:.2f} of overflow in the next {h * 1000:.0f} ms</div></div>",
                    unsafe_allow_html=True)
        actual = row["actual"]
        st.caption("What actually happened: " + ("an overflow occurred within the horizon." if actual == 1 else
                                                 "no overflow within the horizon." if actual == 0 else
                                                 "unknown (horizon extends past the end of the run)."))
    with c2:
        contrib = explain_prediction(b, row)
        st.markdown("**Signals behind this estimate** (logistic-regression contributions)")
        st.markdown(explanation_text(contrib))
        st.dataframe(contrib[["label", "value", "contribution"]], hide_index=True, width="stretch",
                     column_config={"value": st.column_config.NumberColumn(format="%.3f"),
                                    "contribution": st.column_config.NumberColumn(format="%+.2f")})
